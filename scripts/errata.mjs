// Writes notebook/ERRATA.md from site/js/errata.js (the same list the "Notebook check" page shows).
//   npm run errata          regenerate the file
//   npm test                fails if the file is out of date
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { ERRATA, BOOK, SOFTWARE, VERIFIED, SEVERITY } from "../site/js/errata.js";

export const SITE = "https://ysoktar.github.io/graph-theory/";

export function renderErrata() {
  const count = (s) => ERRATA.filter((e) => e.severity === s).length;
  const lines = [
    "# Errata: `Ch2_4_Applied_Tutorial.ipynb`",
    "",
    "Every problem found while re-checking the class notebook *From Graphs to Hubs* for the interactive website.",
    "The notebook itself is unchanged; the website presents the corrected versions.",
    "",
    "**How it was checked.** All code cells were re-executed on the book's data and their printed outputs compared",
    "with the saved ones; every number was recomputed independently (JavaScript library of this site, NetworkX, igraph,",
    "powerlaw); and every claim was compared with the book's text (networksciencebook.com, Chapters 2–5) and with the",
    "notebook's own results. The book was not trusted either: its claims were re-derived or simulated, and the problems",
    "found in it are listed at the end.",
    "",
    "**Locations.** *Cell* counts cells from the top of the notebook (cell 1 is the title). *In [n]* is the execution",
    "count saved with a code cell. The section is the notebook's own heading.",
    "",
    "| Severity | Meaning | Count |",
    "|---|---|---|",
    ...Object.entries(SEVERITY).map(([k, v]) => `| ${v.label} | ${v.desc} | ${count(k)} |`),
    "",
    "## Summary",
    "",
    "| # | Severity | Location | Section | Problem |",
    "|---|---|---|---|---|",
    ...ERRATA.map((e) => `| [${e.id}](#${e.id.toLowerCase()}) | ${SEVERITY[e.severity].label} | cell ${e.cell}${e.run ? `, In [${e.run}]` : ""} | ${e.section} | ${firstSentence(e.issue)} |`),
    "",
    "## Details",
    "",
  ];
  for (const e of ERRATA) {
    lines.push(`### ${e.id}`, "");
    lines.push(`**${SEVERITY[e.severity].label}** · cell ${e.cell}${e.run ? ` (code, In [${e.run}])` : ""} · ${e.section}`, "");
    // quoted verbatim as code, so the notebook's own Markdown is shown rather than interpreted
    lines.push(...e.quote.split("\n").map((l) => `> \`${l}\``), "");
    lines.push(`**Problem.** ${e.issue}`, "");
    lines.push(`**Correction.** ${e.correction}`, "");
    lines.push(`**Evidence.** ${e.evidence}`, "");
    if (e.page) lines.push(`**On the website:** [${e.page.replace(".html", "")}](${SITE}${e.page})`, "");
  }
  lines.push("## Problems found in the book", "",
    "The book (online edition, networksciencebook.com) was not taken as ground truth either. These are the places where it is",
    "wrong, inconsistent, or does not match its own published data, each backed by a derivation or a count on the data.", "",
    "| # | Severity | Location | Problem |", "|---|---|---|---|",
    ...BOOK.map((e) => `| [${e.id}](#${e.id.toLowerCase()}) | ${SEVERITY[e.severity].label} | ${e.location} | ${firstSentence(e.issue)} |`), "");
  for (const e of BOOK) {
    lines.push(`### ${e.id}`, "", `**${SEVERITY[e.severity].label}** · ${e.location}`, "");
    lines.push(...e.quote.split("\n").map((l) => `> \`${l}\``), "");
    lines.push(`**Problem.** ${e.issue}`, "", `**Correction.** ${e.correction}`, "", `**Evidence.** ${e.evidence}`, "");
    if (e.page) lines.push(`**On the website:** [${e.page.replace(".html", "")}](${SITE}${e.page})`, "");
  }
  lines.push("## Problems found in the software", "",
    "The notebook relies on the Python package powerlaw (2.0.0). Two defects in its discrete random generators turned up",
    "while cross-checking this site's bootstrap test. They do not affect the notebook's own outputs, but they do affect anyone",
    "who adds the goodness-of-fit test with powerlaw's generator.", "",
    "| # | Severity | Location | Problem |", "|---|---|---|---|",
    ...SOFTWARE.map((e) => `| [${e.id}](#${e.id.toLowerCase()}) | ${SEVERITY[e.severity].label} | ${e.location} | ${firstSentence(e.issue)} |`), "");
  for (const e of SOFTWARE) {
    lines.push(`### ${e.id}`, "", `**${SEVERITY[e.severity].label}** · ${e.location}`, "");
    lines.push(...e.quote.split("\n").map((l) => `> \`${l}\``), "");
    lines.push(`**Problem.** ${e.issue}`, "", `**Correction.** ${e.correction}`, "", `**Evidence.** ${e.evidence}`, "");
  }
  lines.push("## Checked and found correct", "", ...VERIFIED.map((v) => `- ${v}`), "");
  lines.push("---", "", `Generated by \`npm run errata\` from \`site/js/errata.js\`; also published at ${SITE}notebook-check.html.`, "");
  return lines.join("\n");
}

function firstSentence(s) {
  return s.split(/(?<=[.])\s+(?=[A-Z“(⟨])/)[0].trim().replace(/\|/g, "\\|");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(join(import.meta.dirname, "..", "notebook", "ERRATA.md"), renderErrata());
  console.log(`notebook/ERRATA.md: ${ERRATA.length} entries`);
}
